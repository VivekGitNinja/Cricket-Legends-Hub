export const COUNTRIES = [...new Set(LEGENDS.map((l) => l.country))].sort()
export const ROLES = [...new Set(LEGENDS.map((l) => l.role))].sort()

export function getLegendById(id) {
  return LEGENDS.find((l) => l.id === id) || null
}

export function getLegendByName(name) {
  const n = String(name || '').toLowerCase()
  return LEGENDS.find((l) => l.name.toLowerCase() === n || l.fullName.toLowerCase() === n) || null
}

export function searchLegends(query = '') {
  const q = String(query).trim().toLowerCase()
  if (!q) return LEGENDS
  return LEGENDS.filter((l) =>
    [l.name, l.fullName, l.nickName, l.country, l.role, ...(l.tags || [])]
      .join(' ')
      .toLowerCase()
      .includes(q)
  )
}
